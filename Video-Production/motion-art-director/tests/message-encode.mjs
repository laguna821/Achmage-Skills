import assert from 'node:assert/strict';
import fs from 'node:fs';import os from 'node:os';import path from 'node:path';
import {compositeMessages} from '../lib/message-composite.mjs';
import {run,tool} from '../lib/io.mjs';
const dir=fs.mkdtempSync(path.join(process.env.MOTION_TEST_ROOT||os.tmpdir(),'message-encode-'));
const input=path.join(dir,'input.mp4'),out=path.join(dir,'titled.mp4'),raw=path.join(dir,'frames.rgb');
await run(tool('ffmpeg'),['-nostdin','-v','error','-f','lavfi','-i','color=black:s=640x360:r=30:d=5','-c:v','libx264','-threads','1',input]);
const text="판단은 이어진다. 100% : '한 벌'";
const p={output:{total_frames:150},message_track:{version:'message-track-v1',render_mode:'post-composite',units:[{id:'line',text,start:.5,end:4.5,phrases:[{text,start:.5,end:4.5}]}]}};
await compositeMessages(input,p,out,{width:640,height:360,portrait:false,crf:0});
await run(tool('ffmpeg'),['-nostdin','-v','error','-i',out,'-f','rawvideo','-pix_fmt','rgb24',raw]);
const pixels=fs.readFileSync(raw),size=640*360*3;assert.equal(pixels.length,size*150);
const nonBlack=n=>pixels.subarray(n*size,(n+1)*size).reduce((s,v)=>s+(v>100),0);
for(const n of [0,14,135,149])assert.equal(nonBlack(n),0,'message outside interval '+n);
for(const n of [15,29,134])assert(nonBlack(n)>100,'actual encoded Korean text missing '+n);
const snap=path.join(dir,'snapshot.mp4');
await compositeMessages(input,p,snap,{width:640,height:360,portrait:false,crf:0},{startFrame:29,frames:1});
await run(tool('ffmpeg'),['-nostdin','-v','error','-i',snap,'-f','rawvideo','-pix_fmt','rgb24',path.join(dir,'snapshot.rgb')]);
assert.deepEqual(fs.readFileSync(path.join(dir,'snapshot.rgb')),pixels.subarray(29*size,30*size));
const longOutput=path.join(dir,'title-'+('a'.repeat(170))+'.mp4');
await compositeMessages(input,p,longOutput,{width:640,height:360,portrait:false,crf:0},{startFrame:29,frames:1});
assert(fs.statSync(longOutput).size>0,'long output basename must not become child cwd');
console.log('PASS actual FFmpeg Korean message encode: boundary frames, literals, absolute snapshot identity');
